const supportedLanguages = Object.keys(translations);
const emailCodePoints = {
    user: [106, 111, 110],
    domain: [106, 116, 109, 115, 111, 108, 117, 99, 105, 111, 110, 101, 115, 46, 99, 111, 109]
};
const menuButton = document.querySelector(".menu-toggle");
const siteNav = document.querySelector(".site-nav");

function currentLanguage() {
    return supportedLanguages.includes(document.documentElement.lang) ? document.documentElement.lang : "es";
}

function setMenu(open) {
    if (!menuButton || !siteNav) {
        return;
    }

    const dictionary = translations[currentLanguage()];
    menuButton.setAttribute("aria-expanded", String(open));
    menuButton.setAttribute("aria-label", open ? dictionary["menu.close"] : dictionary["menu.open"]);
    menuButton.querySelector(".material-symbols-outlined").textContent = open ? "close" : "menu";
    siteNav.classList.toggle("is-open", open);
}

function setLanguage(lang, persist = false) {
    const nextLang = supportedLanguages.includes(lang) ? lang : "es";
    const dictionary = translations[nextLang];

    document.documentElement.lang = nextLang;
    document.title = dictionary.metaTitle;
    document.querySelector('meta[name="description"]')?.setAttribute("content", dictionary.metaDescription);

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.getAttribute("data-i18n");
        if (dictionary[key]) {
            element.textContent = dictionary[key];
        }
    });

    document.querySelectorAll("[data-set-lang]").forEach((button) => {
        button.setAttribute("aria-pressed", String(button.dataset.setLang === nextLang));
    });

    if (persist) {
        try {
            localStorage.setItem("jtm-language", nextLang);
        } catch (error) {
            // Language selection still works when storage is unavailable.
        }
    }

    setMenu(false);
}

function detectLanguage() {
    try {
        const saved = localStorage.getItem("jtm-language");
        if (supportedLanguages.includes(saved)) {
            return saved;
        }
    } catch (error) {
        // Continue with browser detection.
    }

    const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
    const normalized = languages.filter(Boolean).map((language) => language.toLowerCase());

    if (normalized.some((language) => language === "ja" || language.startsWith("ja-"))) {
        return "ja";
    }

    if (normalized.some((language) => language === "es" || language.startsWith("es-"))) {
        return "es";
    }

    return "en";
}

function emailAddress() {
    const decode = (points) => String.fromCharCode(...points);
    return `${decode(emailCodePoints.user)}@${decode(emailCodePoints.domain)}`;
}

function initContactForm() {
    const form = document.querySelector("[data-contact-form]");
    if (!form) {
        return;
    }

    form.addEventListener("submit", (event) => {
        event.preventDefault();

        if (!form.reportValidity()) {
            return;
        }

        const dictionary = translations[currentLanguage()];
        const data = new FormData(form);
        const name = String(data.get("name") ?? "").trim();
        const replyTo = String(data.get("email") ?? "").trim();
        const message = String(data.get("message") ?? "").trim();
        const subject = `${dictionary["contact.form.subject"]}: ${name}`;
        const body = `${dictionary["contact.form.name"]}: ${name}\n${dictionary["contact.form.email"]}: ${replyTo}\n\n${dictionary["contact.form.message"]}\n${message}`;

        window.location.href = `mailto:${emailAddress()}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
    });
}

menuButton?.addEventListener("click", () => {
    setMenu(menuButton.getAttribute("aria-expanded") !== "true");
});

siteNav?.addEventListener("click", (event) => {
    if (event.target.closest("a")) {
        setMenu(false);
    }
});

document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
        setMenu(false);
    }
});

document.querySelectorAll("[data-set-lang]").forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.setLang, true));
});

document.getElementById("year").textContent = new Date().getFullYear();
initContactForm();
setLanguage(detectLanguage());
