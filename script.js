const githubUsername = "vorvek";
const githubStatsCacheUrl = "/github-stats.json?v=20260606-public";
const githubStatsCacheKey = "jtm-github-stats";
const githubStatsCacheTtlMs = 60 * 60 * 1000;
const githubStatsState = {
    status: "loading",
    data: null,
    cachedAt: 0
};
const emailCodePoints = {
    user: [106, 111, 110],
    domain: [106, 116, 109, 115, 111, 108, 117, 99, 105, 111, 110, 101, 115, 46, 99, 111, 109]
};
const spanishTimeZones = new Set(["Europe/Madrid", "Atlantic/Canary"]);
const spanishLocales = new Set(["es-es", "ca-es", "eu-es", "gl-es"]);

function setLanguage(lang, persist = false) {
    const nextLang = lang === "en" ? "en" : "es";
    const dictionary = translations[nextLang];

    document.documentElement.lang = nextLang;
    document.title = dictionary.metaTitle;

    const description = document.querySelector('meta[name="description"]');
    if (description) {
        description.setAttribute("content", dictionary.metaDescription);
    }

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.getAttribute("data-i18n");
        if (dictionary[key]) {
            element.textContent = dictionary[key];
        }
    });

    document.querySelectorAll("[data-set-lang]").forEach((button) => {
        button.setAttribute("aria-pressed", String(button.dataset.setLang === nextLang));
    });

    if (persist) {
        try {
            localStorage.setItem("jtm-language", nextLang);
        } catch (error) {
            // Some privacy modes block storage; language still updates for this page view.
        }
    }

    renderGithubStats();
    hydrateEmailLinks();
}

function browserLooksSpanish() {
    const timeZone = Intl.DateTimeFormat().resolvedOptions().timeZone;
    const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
    const hasSpanishLocale = languages
        .filter(Boolean)
        .map((language) => language.toLowerCase())
        .some((language) => spanishLocales.has(language));

    return spanishTimeZones.has(timeZone) || hasSpanishLocale;
}

function currentLanguage() {
    return document.documentElement.lang === "en" ? "en" : "es";
}

function translate(key) {
    return translations[currentLanguage()]?.[key] ?? translations.es[key] ?? key;
}

function formatStat(value) {
    if (!Number.isFinite(value)) {
        return "...";
    }

    return new Intl.NumberFormat(currentLanguage()).format(value);
}

function renderGithubStats() {
    const stats = githubStatsState.data;
    const values = {
        repositories: stats?.repositories,
        stars: stats?.stars,
        commits: stats?.commits,
        followers: stats?.followers
    };

    document.querySelectorAll("[data-github-stat]").forEach((element) => {
        const statName = element.getAttribute("data-github-stat");
        element.textContent = formatStat(values[statName]);
    });

    const status = document.querySelector("[data-github-status]");
    if (!status) {
        return;
    }

    const statusKey = githubStatsState.status === "ready"
        ? "github.stats.ready"
        : githubStatsState.status === "stale"
            ? "github.stats.stale"
        : githubStatsState.status === "error"
            ? "github.stats.unavailable"
            : "github.stats.loading";

    status.textContent = translate(statusKey);
}

function normalizeGithubStatsCache(payload) {
    const rawStats = payload?.data ?? payload;
    const data = {
        repositories: normalizeGithubStat(rawStats?.repositories),
        stars: normalizeGithubStat(rawStats?.stars),
        commits: normalizeGithubStat(rawStats?.commits),
        followers: normalizeGithubStat(rawStats?.followers)
    };
    const hasAllStats = Object.values(data).every((value) => value !== null);
    const cachedAt = Date.parse(payload?.cachedAt ?? payload?.fetchedAt ?? payload?.updatedAt ?? "");

    if (!hasAllStats || !Number.isFinite(cachedAt)) {
        return null;
    }

    return { data, cachedAt };
}

function normalizeGithubStat(value) {
    const number = Number(value);
    if (!Number.isFinite(number) || number < 0) {
        return null;
    }

    return Math.round(number);
}

function githubStatsCacheStatus(cache) {
    return Date.now() - cache.cachedAt < githubStatsCacheTtlMs ? "ready" : "stale";
}

function newerGithubStatsCache(left, right) {
    if (!left) {
        return right;
    }

    if (!right) {
        return left;
    }

    return right.cachedAt > left.cachedAt ? right : left;
}

function readStoredGithubStatsCache() {
    try {
        return normalizeGithubStatsCache(JSON.parse(localStorage.getItem(githubStatsCacheKey)));
    } catch (error) {
        return null;
    }
}

function writeStoredGithubStatsCache(cache) {
    try {
        localStorage.setItem(githubStatsCacheKey, JSON.stringify({
            cachedAt: new Date(cache.cachedAt).toISOString(),
            data: cache.data
        }));
    } catch (error) {
        // Some privacy modes block storage; the in-memory cache still works for this view.
    }
}

function applyGithubStatsCache(cache, status = githubStatsCacheStatus(cache)) {
    githubStatsState.data = cache.data;
    githubStatsState.cachedAt = cache.cachedAt;
    githubStatsState.status = status;
    renderGithubStats();
}

async function fetchSeedGithubStatsCache(signal) {
    const response = await fetch(githubStatsCacheUrl, {
        cache: "force-cache",
        signal
    });

    if (!response.ok) {
        throw new Error(`GitHub stats cache returned ${response.status}`);
    }

    return normalizeGithubStatsCache(await response.json());
}

async function fetchGithubJson(url, signal) {
    const response = await fetch(url, {
        headers: {
            Accept: "application/vnd.github+json"
        },
        cache: "no-store",
        signal
    });

    if (!response.ok) {
        throw new Error(`GitHub API returned ${response.status}`);
    }

    return response.json();
}

async function loadGithubStats() {
    if (!document.querySelector("[data-github-stats]")) {
        return;
    }

    let cache = readStoredGithubStatsCache();
    if (cache) {
        applyGithubStatsCache(cache);
    } else {
        renderGithubStats();
    }

    const controller = new AbortController();
    const timeout = window.setTimeout(() => controller.abort(), 6000);

    try {
        cache = newerGithubStatsCache(cache, await fetchSeedGithubStatsCache(controller.signal));
        if (cache) {
            applyGithubStatsCache(cache);
            writeStoredGithubStatsCache(cache);
        }
    } catch (error) {
        // Missing or blocked seed files should not prevent a public refresh attempt.
    }

    if (cache && githubStatsCacheStatus(cache) === "ready") {
        window.clearTimeout(timeout);
        return;
    }

    renderGithubStats();

    try {
        const [profile, repos, commits] = await Promise.all([
            fetchGithubJson(`https://api.github.com/users/${githubUsername}`, controller.signal),
            fetchGithubJson(`https://api.github.com/users/${githubUsername}/repos?per_page=100&type=owner&sort=pushed`, controller.signal),
            fetchGithubJson(`https://api.github.com/search/commits?q=author:${githubUsername}`, controller.signal)
        ]);
        const publicRepos = Array.isArray(repos) ? repos : [];

        githubStatsState.data = {
            repositories: Number(profile.public_repos) || publicRepos.length,
            stars: publicRepos.reduce((total, repo) => total + (Number(repo.stargazers_count) || 0), 0),
            commits: Number(commits.total_count) || 0,
            followers: Number(profile.followers) || 0
        };
        githubStatsState.cachedAt = Date.now();
        githubStatsState.status = "ready";
        writeStoredGithubStatsCache({
            cachedAt: githubStatsState.cachedAt,
            data: githubStatsState.data
        });
    } catch (error) {
        if (cache) {
            applyGithubStatsCache(cache, "stale");
        } else {
            githubStatsState.status = "error";
        }
    } finally {
        window.clearTimeout(timeout);
        renderGithubStats();
    }
}

function initGithubStats() {
    const statsElement = document.querySelector("[data-github-stats]");
    if (!statsElement) {
        return;
    }

    const triggerElement = document.querySelector("#contacto") ?? statsElement;
    let observer = null;
    let started = false;

    function cleanup() {
        observer?.disconnect();
        window.removeEventListener("scroll", maybeLoadStats);
        window.removeEventListener("resize", maybeLoadStats);
        window.removeEventListener("hashchange", maybeLoadStats);
    }

    function startLoading() {
        if (started) {
            return;
        }

        started = true;
        cleanup();
        loadGithubStats();
    }

    function statsAreNearViewport() {
        const rect = triggerElement.getBoundingClientRect();
        return rect.top < window.innerHeight + 420 && rect.bottom > -420;
    }

    function maybeLoadStats() {
        if (location.hash === "#contacto" || statsAreNearViewport()) {
            startLoading();
        }
    }

    renderGithubStats();

    if ("IntersectionObserver" in window) {
        observer = new IntersectionObserver((entries) => {
            if (entries.some((entry) => entry.isIntersecting)) {
                startLoading();
            }
        }, { rootMargin: "420px 0px" });

        observer.observe(triggerElement);
    }

    window.addEventListener("scroll", maybeLoadStats, { passive: true });
    window.addEventListener("resize", maybeLoadStats);
    window.addEventListener("hashchange", maybeLoadStats);
    maybeLoadStats();
}

function decodeEmailPart(points) {
    return String.fromCharCode(...points);
}

function getEmailAddress() {
    return `${decodeEmailPart(emailCodePoints.user)}@${decodeEmailPart(emailCodePoints.domain)}`;
}

function hydrateEmailLinks() {
    const emailAddress = getEmailAddress();

    document.querySelectorAll("[data-email-link]").forEach((link) => {
        const subject = link.getAttribute("data-email-subject");
        const query = subject ? `?subject=${encodeURIComponent(subject)}` : "";
        link.setAttribute("href", `mailto:${emailAddress}${query}`);
    });

    document.querySelectorAll("[data-email-text]").forEach((element) => {
        element.textContent = emailAddress;
    });
}

function detectLanguage() {
    let savedLanguage = null;

    try {
        savedLanguage = localStorage.getItem("jtm-language");
    } catch (error) {
        savedLanguage = null;
    }

    if (savedLanguage) {
        setLanguage(savedLanguage);
        return;
    }

    setLanguage(browserLooksSpanish() ? "es" : "en");
}

document.querySelectorAll("[data-set-lang]").forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.setLang, true));
});

document.getElementById("year").textContent = new Date().getFullYear();
hydrateEmailLinks();
detectLanguage();
initGithubStats();
